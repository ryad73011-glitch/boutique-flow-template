-- Core multi-store schema for a future authenticated merchant dashboard.
-- This migration is intentionally not deployed by the storefront build workflow.
-- Prices are whole Algerian dinars (DZD); WhatsApp checkout remains separate.

create extension if not exists pgcrypto;

create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (length(trim(name)) between 1 and 120),
  name_ar text,
  currency_code text not null default 'DZD' check (currency_code ~ '^[A-Z]{3}$'),
  whatsapp_phone text,
  is_published boolean not null default false,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_memberships (
  store_id uuid not null references public.stores(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'admin', 'editor')),
  created_at timestamptz not null default now(),
  primary key (store_id, user_id)
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  sku text,
  name_fr text not null check (length(trim(name_fr)) between 1 and 180),
  name_ar text,
  description_fr text,
  description_ar text,
  price_dzd bigint not null check (price_dzd >= 0),
  image_url text,
  sizes text[] not null default '{}',
  inventory_quantity integer check (inventory_quantity is null or inventory_quantity >= 0),
  track_inventory boolean not null default false,
  status text not null default 'draft' check (status in ('draft', 'active', 'archived')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, slug),
  unique (store_id, id)
);

create unique index if not exists products_store_sku_unique
  on public.products (store_id, sku)
  where sku is not null and length(trim(sku)) > 0;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  order_number bigint generated by default as identity,
  customer_name text not null check (length(trim(customer_name)) between 1 and 120),
  customer_phone text not null check (length(trim(customer_phone)) between 5 and 40),
  delivery_wilaya text,
  delivery_address text,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'preparing', 'shipped', 'completed', 'cancelled')),
  total_dzd bigint not null default 0 check (total_dzd >= 0),
  notes text,
  source text not null default 'manual' check (source in ('manual', 'whatsapp', 'other')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, order_number),
  unique (store_id, id)
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null,
  order_id uuid not null,
  product_id uuid,
  product_name text not null check (length(trim(product_name)) between 1 and 180),
  product_reference text,
  selected_size text,
  quantity integer not null check (quantity between 1 and 999),
  unit_price_dzd bigint not null check (unit_price_dzd >= 0),
  created_at timestamptz not null default now(),
  constraint order_items_order_store_fk
    foreign key (store_id, order_id) references public.orders(store_id, id) on delete cascade,
  constraint order_items_product_store_fk
    foreign key (store_id, product_id) references public.products(store_id, id) on delete set null
);

create index if not exists products_store_status_sort_idx
  on public.products (store_id, status, sort_order);
create index if not exists orders_store_created_idx
  on public.orders (store_id, created_at desc);
create index if not exists orders_store_status_idx
  on public.orders (store_id, status);
create index if not exists order_items_order_idx
  on public.order_items (store_id, order_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists stores_set_updated_at on public.stores;
create trigger stores_set_updated_at before update on public.stores
for each row execute function public.set_updated_at();

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at before update on public.products
for each row execute function public.set_updated_at();

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at before update on public.orders
for each row execute function public.set_updated_at();

-- SECURITY DEFINER avoids recursive RLS evaluation when policies inspect memberships.
create or replace function public.has_store_role(p_store_id uuid, p_roles text[])
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.store_memberships m
    where m.store_id = p_store_id
      and m.user_id = (select auth.uid())
      and m.role = any (p_roles)
  );
$$;

revoke all on function public.has_store_role(uuid, text[]) from public;
grant execute on function public.has_store_role(uuid, text[]) to authenticated;

-- A store creator becomes its owner atomically. Clients cannot grant themselves roles.
create or replace function public.add_store_creator_as_owner()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.store_memberships (store_id, user_id, role)
  values (new.id, new.created_by, 'owner')
  on conflict (store_id, user_id) do nothing;
  return new;
end;
$$;

revoke all on function public.add_store_creator_as_owner() from public;
drop trigger if exists stores_add_creator_as_owner on public.stores;
create trigger stores_add_creator_as_owner after insert on public.stores
for each row execute function public.add_store_creator_as_owner();

alter table public.stores enable row level security;
alter table public.store_memberships enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Published storefronts and active products are public; draft data is private.
drop policy if exists stores_read_published_or_member on public.stores;
create policy stores_read_published_or_member on public.stores
for select using (
  is_published or public.has_store_role(id, array['owner', 'admin', 'editor'])
);

drop policy if exists stores_create_as_self on public.stores;
create policy stores_create_as_self on public.stores
for insert to authenticated
with check (created_by = (select auth.uid()));

drop policy if exists stores_update_admin on public.stores;
create policy stores_update_admin on public.stores
for update to authenticated
using (public.has_store_role(id, array['owner', 'admin']))
with check (public.has_store_role(id, array['owner', 'admin']));

drop policy if exists stores_delete_owner on public.stores;
create policy stores_delete_owner on public.stores
for delete to authenticated
using (public.has_store_role(id, array['owner']));

drop policy if exists memberships_read_self_or_member on public.store_memberships;
create policy memberships_read_self_or_member on public.store_memberships
for select to authenticated
using (
  user_id = (select auth.uid())
  or public.has_store_role(store_id, array['owner', 'admin', 'editor'])
);

-- Deliberately no client-side membership insert/update/delete policies.
-- Provisioning additional staff must be added through a trusted server-side flow.

drop policy if exists products_read_active_or_member on public.products;
create policy products_read_active_or_member on public.products
for select using (
  (status = 'active' and exists (
    select 1 from public.stores s where s.id = store_id and s.is_published
  ))
  or public.has_store_role(store_id, array['owner', 'admin', 'editor'])
);

drop policy if exists products_insert_member on public.products;
create policy products_insert_member on public.products
for insert to authenticated
with check (public.has_store_role(store_id, array['owner', 'admin', 'editor']));

